/* Generates the scale/grade block in ui-energy.css from data/scales.json. Run: node scales.build.js · Docs: readme.md */
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('.', import.meta.url).pathname;
const { colours, fallback, scales, types } = JSON.parse(readFileSync(dir + 'data/scales.json', 'utf8'));
const letters = 'abcdefg';
const stop = (i) => `var(--ui-energy-${letters[i]})`;

/* class i of n -> one of the seven arrow colours, or an oklab mix of the two around it */
const colourAt = (i, n) => {
	const p = n === 1 ? 0 : (i / (n - 1)) * (colours.length - 1);
	const lo = Math.floor(p), hi = Math.ceil(p), f = p - lo;
	if (lo === hi || f < 0.005) return stop(lo);
	if (f > 0.995) return stop(hi);
	return `color-mix(in oklab, ${stop(lo)} ${Math.round((1 - f) * 100)}%, ${stop(hi)})`;
};

const out = ['\t\t/* scales:start */', '\t\t/* generated by scales.build.js from data/scales.json — do not edit */'];
for (const [name, classes] of Object.entries(scales)) {
	const t = Object.keys(types).filter((k) => types[k] === name).map((k) => `[type="${k}"]`);
	const sel = [`[scale="${name}"]`];
	if (t.length) sel.push(`:not([scale]):is(${t.join(', ')})`);
	if (name === fallback) sel.push(':not([scale], [type])');
	const is = `&:is(${sel.join(', ')})`;
	out.push('', `\t\t${is} { --_top: "${classes[0]}"; --_end: "${classes.at(-1)}"; }`);
	classes.forEach((c, i) => out.push(`\t\t${is}[grade="${c}"] { --_c: ${colourAt(i, classes.length)}; }`));
}
out.push('\t\t/* scales:end */');

const file = dir + 'ui-energy.css';
const css = readFileSync(file, 'utf8');
const next = css.replace(/\t\t\/\* scales:start \*\/[\s\S]*?\/\* scales:end \*\//, out.join('\n'));
if (next === css) console.log('ui-energy.css: no change');
else { writeFileSync(file, next); console.log('ui-energy.css: scales regenerated'); }
