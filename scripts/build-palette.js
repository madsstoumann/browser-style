#!/usr/bin/env node
/* Palette builder — ui/base/palette.json is the one source; everything else here is generated from it.
 *
 *   node scripts/build-palette.js            rewrite the generated blocks, write palette.rules.json, print the contrast report
 *   node scripts/build-palette.js --check    change nothing; exit 1 if any block or palette.rules.json is out of date
 *   node scripts/build-palette.js --quiet    skip the contrast report
 *
 * A generated block lives between `/* palette:start *\/` and `/* palette:end *\/` in each target file (the
 * markers are written by hand once; the text between them is replaced on every run, so a second run changes nothing).
 *
 * Colours are `<hue>-<step>` (Tailwind names and steps). `accent` is an alias hue that points at one real hue;
 * `white` and `black` are fixed colours with no steps. Dark pages mirror the steps (50<->950, 100<->900, ...),
 * so every variable is a light-dark() pair of a step and its mirror.
 *
 * No dependencies. ESM.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'ui/base/palette.json';
const flags = new Set(process.argv.slice(2));
const CHECK = flags.has('--check');
const QUIET = flags.has('--quiet');
const GENERATED = `/* generated by scripts/build-palette.js from ${SOURCE} — do not edit */`;

/* ── source ── */

const palette = JSON.parse(readFileSync(resolve(root, SOURCE), 'utf8'));
const STEPS = palette.steps.map(Number);
const mirror = (step) => STEPS[STEPS.length - 1 - STEPS.indexOf(step)];
const HUES = Object.keys(palette.hues);
const RESERVED = ['accent', 'white', 'black'];
const WORDS = Object.keys(palette.fixed);

for (const hue of HUES) {
	if (!/^[a-z]+$/.test(hue) || RESERVED.includes(hue)) throw new Error(`palette: "${hue}" is not a valid hue name (one lowercase word, letters only, not ${RESERVED.join('/')})`);
	for (const step of STEPS) if (typeof palette.hues[hue][step] !== 'string') throw new Error(`palette: ${hue}-${step} has no value`);
}
if (!HUES.includes(palette.accent)) throw new Error(`palette: accent points at "${palette.accent}", which is not a hue`);

/* the hues that get rules: accent first (it leads every colour row), then the real hues */
const RULE_HUES = ['accent', ...HUES];
const COLOURS = [
	...RULE_HUES.flatMap((hue) => STEPS.map((step) => `${hue}-${step}`)),
	...WORDS
];

/* ── colour maths (WCAG 2): oklch / hex -> sRGB, clipped to gamut -> relative luminance ── */

function linearRgb(value) {
	const hex = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(value);
	if (hex) {
		const h = hex[1].length === 3 ? [...hex[1]].map((c) => c + c).join('') : hex[1];
		return [0, 2, 4].map((i) => {
			const c = parseInt(h.slice(i, i + 2), 16) / 255;
			return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
		});
	}
	const m = /^oklch\(\s*([\d.]+)%\s+([\d.]+)\s+([\d.]+)\s*\)$/.exec(value);
	if (!m) throw new Error(`palette: cannot read colour "${value}" (oklch() or #hex)`);
	const L = m[1] / 100, a = m[2] * Math.cos(m[3] * Math.PI / 180), b = m[2] * Math.sin(m[3] * Math.PI / 180);
	const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
	const mm = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
	const s = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3;
	return [
		4.0767416621 * l - 3.3077115913 * mm + 0.2309699292 * s,
		-1.2684380046 * l + 2.6097574011 * mm - 0.3413193965 * s,
		-0.0041960863 * l - 0.7034186147 * mm + 1.7076147010 * s
	].map((c) => Math.min(1, Math.max(0, c)));
}
const luminance = (value) => { const [r, g, b] = linearRgb(value); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const ratio = (a, b) => (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);

/* ── values ── */

/* a hue's literal value, or a literal given as is ("gray-950" -> its oklch(), "#fff" -> "#fff") */
function literal(ref) {
	const m = /^([a-z]+)-(\d+)$/.exec(ref);
	return m ? palette.hues[m[1]][m[2]] : ref;
}

/* text on a step: the hue's 950 if it reaches the minimum, else black or white, whichever reads better */
function textOn(hue, step) {
	const fill = luminance(palette.hues[hue][step]);
	const preferred = palette.hues[hue][palette.text.prefer];
	if (ratio(fill, luminance(preferred)) >= palette.text.min) return preferred;
	return ratio(fill, 1) >= ratio(fill, 0) ? '#fff' : '#000';
}

const fixedText = (word) => literal(palette.fixed[word].text);
const pair = (a, b) => `light-dark(${a}, ${b})`;

/* ── rule templates (the single definition: rendered into the files and written to palette.rules.json) ──
   per:   what {name} is — hue ("green"), colour ("green-300"), step ("300"), word ("white")
   ships: browser-style carries the rule for its own names; false = a CMS emits it for a hue it adds */

const STEP_DECLS = (prefix, value, text) => STEPS.flatMap((s) => (text
	? [`${prefix}-${s}: ${value(s)}`, `${prefix}-${s}-c: ${text(s)}`]
	: [`${prefix}-${s}: ${value(s)}`]));

const RULES = [
	/* theme= / data-theme= */
	{
		id: 'theme-word', file: palette.targets.theme, layer: 'bs-core', per: 'word', emitForAddedHue: false,
		selector: ':where([theme~="{name}"], [data-theme~="{name}"])',
		declarations: ['--_theme-base-bg: var(--color-{name})', '--_theme-base-c: var(--color-{name}-text)']
	},
	{
		id: 'theme-hue', file: palette.targets.theme, layer: 'bs-core', per: 'hue', emitForAddedHue: true,
		selector: ':where([theme^="{name}-"], [theme*=" {name}-"], [data-theme^="{name}-"], [data-theme*=" {name}-"])',
		declarations: STEP_DECLS('--_theme', (s) => `var(--color-{name}-${s})`, (s) => `var(--color-{name}-${s}-text)`)
	},
	{
		id: 'theme-step', file: palette.targets.theme, layer: 'bs-core', per: 'step', emitForAddedHue: false,
		selector: ':where([theme$="-{name}"], [theme*="-{name} "], [data-theme$="-{name}"], [data-theme*="-{name} "])',
		declarations: ['--_theme-base-bg: var(--_theme-{name})', '--_theme-base-c: var(--_theme-{name}-c)']
	},
	/* dark pins the page's dark arm to the element, which mirrors every step: the mirror step, resolved dark, is the pick as written (gray-800 dark = a dark plate) */
	{
		id: 'theme-step-dark', file: palette.targets.theme, layer: 'bs-core', per: 'step', emitForAddedHue: false,
		selector: ':where([theme~="dark"]:is([theme$="-{name}"], [theme*="-{name} "]), [data-theme~="dark"]:is([data-theme$="-{name}"], [data-theme*="-{name} "]))',
		declarations: ['--_theme-base-bg: var(--_theme-{mirror})', '--_theme-base-c: var(--_theme-{mirror}-c)']
	},
	/* tint= / tint-end= — single-valued, so hue ^= and step $= */
	...[['tint', '--_tint'], ['tint-end', '--_tint-end']].flatMap(([attr, prop]) => [
		{
			id: `${attr}-word`, file: palette.targets.tint, layer: 'bs-core', per: 'word', emitForAddedHue: false,
			selector: `:where([${attr}="{name}"], [data-${attr}="{name}"])`,
			declarations: [`${prop}: var(--color-{name})`]
		},
		{
			id: `${attr}-hue`, file: palette.targets.tint, layer: 'bs-core', per: 'hue', emitForAddedHue: true,
			selector: `:where([${attr}^="{name}-"], [data-${attr}^="{name}-"])`,
			declarations: STEP_DECLS(prop, (s) => `var(--color-{name}-${s})`)
		},
		{
			id: `${attr}-step`, file: palette.targets.tint, layer: 'bs-core', per: 'step', emitForAddedHue: false,
			selector: `:where([${attr}$="-{name}"], [data-${attr}$="-{name}"])`,
			declarations: [`${prop}: var(${prop}-{name})`]
		}
	]),
	/* furniture — one media= attribute holds hue and step, so one rule per colour */
	...palette.targets.furniture.map(({ name, file, kind, vars }) => {
		const base = { id: `${name}-colour`, file, layer: 'bs-component', per: 'colour', emitForAddedHue: true };
		const declarations = vars.map((v, i) => `${v}: var(--color-{name}${i ? '-text' : ''})`);
		const token = `[media*="${name}({name})"]`;
		if (kind === 'nested') {
			return { ...base, scope: `:where(ui-${name})`, nested: `:where(${token}) &`, selector: `:where(${token}) :where(ui-${name})`, declarations };
		}
		if (kind === 'descendant') return { ...base, selector: `:where(${token} ui-${name})`, declarations };
		if (kind === 'host') return { ...base, selector: `:where(${token})`, declarations };
		throw new Error(`palette: furniture "${name}" has an unknown kind "${kind}"`);
	})
];

const namesFor = { hue: RULE_HUES, colour: COLOURS, step: STEPS.map(String), word: WORDS };
const fill = (template, name) => template.replaceAll('{name}', name).replaceAll('{mirror}', /^\d+$/.test(name) ? mirror(Number(name)) : '{mirror}');

function render(rule, name) {
	const selector = fill(rule.nested ?? rule.selector, name);
	const decls = rule.declarations.map((d) => fill(d, name));
	if (decls.length <= 2) return [`${selector} { ${decls.join('; ')}; }`];
	return [`${selector} {`, ...decls.map((d) => `\t${d};`), '}'];
}

/* the lines of one block: every rule of the file, each rendered for every name it applies to */
function rulesBlock(file) {
	const lines = [GENERATED];
	for (const rule of RULES.filter((r) => r.file === file)) {
		const multi = rule.declarations.length > 2;
		const body = namesFor[rule.per].map((name) => render(rule, name));
		lines.push('', ...(multi ? body.flatMap((l, i) => (i ? ['', ...l] : l)) : body.flat()));
	}
	return lines;
}

function tokensBlock() {
	const lines = [GENERATED];
	for (const hue of HUES) {
		lines.push('');
		for (const step of STEPS) {
			const other = mirror(step);
			lines.push(`--color-${hue}-${step}: ${pair(palette.hues[hue][step], palette.hues[hue][other])};`);
			lines.push(`--color-${hue}-${step}-text: ${pair(textOn(hue, step), textOn(hue, other))};`);
		}
	}
	lines.push('');
	for (const step of STEPS) {
		lines.push(`--color-accent-${step}: var(--color-${palette.accent}-${step});`);
		lines.push(`--color-accent-${step}-text: var(--color-${palette.accent}-${step}-text);`);
	}
	lines.push('');
	for (const word of WORDS) {
		lines.push(`--color-${word}: ${palette.fixed[word].value};`);
		lines.push(`--color-${word}-text: ${fixedText(word)};`);
	}
	return lines;
}

/* ── palette.rules.json — what a CMS needs to write the same rules for a hue a designer adds ── */

function rulesJson() {
	const placeholders = {
		'{name}': 'what the rule is written for, by "per": hue = "green", colour = "green-300", step = "300", word = "white"',
		'{mirror}': 'in a per-step rule: the mirror of that step (50<->950, 100<->900, 200<->800, 300<->700, 400<->600, 500<->500)',
		'{mirror-value}': 'in variables: the value of the mirror step',
		'{value}': 'the colour on the page-light arm, as written in palette.json (oklch())',
		'{text}': 'the readable text colour on {value}, by the "text" rule below',
		'{mirror-text}': 'the readable text colour on {mirror-value}'
	};
	return {
		$comment: `Generated by scripts/build-palette.js from ${SOURCE} — do not edit. Each rule is flat CSS: emit "selector { declarations }" inside @layer "layer", once per name its "per" asks for. A hue a designer adds needs the rules with emitForAddedHue: true; the others ship once with browser-style. "nested" is the same selector as written inside the component's own block, where & stands for "scope".`,
		steps: STEPS,
		mirror: Object.fromEntries(STEPS.map((s) => [s, mirror(s)])),
		accent: palette.accent,
		fixed: Object.fromEntries(WORDS.map((w) => [w, { value: palette.fixed[w].value, text: fixedText(w) }])),
		text: {
			prefer: palette.text.prefer,
			min: palette.text.min,
			rule: 'text on a step = the hue\'s 950 value if its WCAG 2 contrast with the step is >= min, else #000 or #fff, whichever has the higher contrast (oklch -> sRGB clipped to gamut -> relative luminance)'
		},
		placeholders,
		variables: {
			per: 'colour', layer: 'bs-core', selector: ':root', emitForAddedHue: true,
			declarations: ['--color-{name}: light-dark({value}, {mirror-value})', '--color-{name}-text: light-dark({text}, {mirror-text})']
		},
		rules: RULES.map(({ id, file, layer, per, emitForAddedHue, selector, nested, scope, declarations }) => ({
			id, per, file, layer, emitForAddedHue, selector, ...(nested ? { nested, scope } : {}), declarations
		}))
	};
}

/* ── writing ── */

function inject(file, lines) {
	const path = resolve(root, file);
	const text = readFileSync(path, 'utf8');
	const re = /^([ \t]*)\/\* palette:start \*\/[ \t]*\n[\s\S]*?\n?[ \t]*\/\* palette:end \*\/[ \t]*$/m;
	const starts = text.split('/* palette:start */').length - 1;
	const ends = text.split('/* palette:end */').length - 1;
	if (starts !== 1 || ends !== 1) throw new Error(`${file}: expected exactly one /* palette:start */ and one /* palette:end */ marker (found ${starts} and ${ends})`);
	const match = re.exec(text);
	if (!match) throw new Error(`${file}: palette markers are not on lines of their own`);
	const indent = match[1];
	const body = lines.map((l) => (l ? indent + l : '')).join('\n');
	const block = `${indent}/* palette:start */\n${body}\n${indent}/* palette:end */`;
	return { path, text, next: text.slice(0, match.index) + block + text.slice(match.index + match[0].length), bytes: Buffer.byteLength(body) + 1 };
}

const results = [];
function write(label, path, text, next, bytes) {
	const changed = text !== next;
	if (changed && !CHECK) writeFileSync(path, next);
	results.push({ label, changed, bytes, size: Buffer.byteLength(next) });
}

const jobs = [
	[palette.targets.tokens, tokensBlock()],
	[palette.targets.theme, rulesBlock(palette.targets.theme)],
	[palette.targets.tint, rulesBlock(palette.targets.tint)],
	...palette.targets.furniture.map(({ file }) => [file, rulesBlock(file)])
];
for (const [file, lines] of jobs) {
	const { path, text, next, bytes } = inject(file, lines);
	write(file, path, text, next, bytes);
}

const rulesPath = resolve(root, palette.targets.rules);
const rulesText = JSON.stringify(rulesJson(), null, 2) + '\n';
let current = '';
try { current = readFileSync(rulesPath, 'utf8'); } catch { /* first run */ }
write(palette.targets.rules, rulesPath, current, rulesText, Buffer.byteLength(rulesText));

/* ── report ── */

const pad = (s, n) => String(s).padEnd(n);
console.log(`palette: ${HUES.length} hues x ${STEPS.length} steps + accent (-> ${palette.accent}) + ${WORDS.join(', ')} = ${COLOURS.length} colours`);
for (const r of results) console.log(`  ${r.changed ? (CHECK ? 'STALE  ' : 'updated') : 'ok     '}  ${pad(r.label, 34)} block ${String(r.bytes).padStart(6)} B   file ${String(r.size).padStart(6)} B`);

if (!QUIET) {
	const rows = [];
	for (const hue of HUES) {
		for (const step of STEPS) {
			const text = textOn(hue, step);
			rows.push({ name: `${hue}-${step}`, hue, ratio: ratio(luminance(palette.hues[hue][step]), luminance(text)), text });
		}
	}
	for (const word of WORDS) rows.push({ name: word, hue: word, ratio: ratio(luminance(palette.fixed[word].value), luminance(fixedText(word))), text: fixedText(word) });
	const kind = (r) => (r.text === '#fff' ? 'white' : r.text === '#000' ? 'black' : '950');
	const count = { 950: 0, white: 0, black: 0 };
	for (const r of rows) count[kind(r)]++;
	const sorted = [...rows].sort((a, b) => a.ratio - b.ratio);
	const under = rows.filter((r) => r.ratio < palette.text.min);
	console.log(`contrast (text on fill, WCAG 2, min ${palette.text.min}): ${rows.length} colours, ${under.length} under; text is the hue's 950 on ${count[950]}, white on ${count.white}, black on ${count.black}`);
	console.log('  lowest: ' + sorted.slice(0, 5).map((r) => `${r.name} ${r.ratio.toFixed(2)} (${kind(r)})`).join(', '));
	console.log('  per hue: ' + HUES.map((h) => {
		const low = rows.filter((r) => r.hue === h).sort((a, b) => a.ratio - b.ratio)[0];
		return `${h} ${low.ratio.toFixed(1)}@${low.name.split('-')[1]}`;
	}).join(', '));
	for (const r of under) console.log(`  UNDER ${palette.text.min}: ${r.name} ${r.ratio.toFixed(2)}`);
}

const changed = results.filter((r) => r.changed);
if (CHECK) {
	if (changed.length) { console.error(`palette: ${changed.length} file(s) out of date — run node scripts/build-palette.js`); process.exit(1); }
	console.log('palette: up to date');
} else {
	console.log(changed.length ? `palette: ${changed.length} file(s) updated` : 'palette: no change');
}
