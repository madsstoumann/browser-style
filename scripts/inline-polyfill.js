/* Inline the typed-attr() polyfill into the pages listed in PAGES (today: one).
 *
 *   node scripts/inline-polyfill.js [--check]
 *
 * WHY: ui/base/polyfills/attr-fallback.js must run BEFORE first paint — a cross-document
 * view transition snapshots the incoming page there, so a late patch means unnamed morph
 * targets and a degraded cross-fade. That is why pages loaded it with blocking="render".
 * But in Chrome the polyfill feature-detects and does nothing, so the page paid a full
 * render-blocking round trip for a no-op. Inlining removes the request entirely and keeps
 * the before-paint guarantee for free. Docs: docs/performance.md § JavaScript and the polyfill
 *
 * TWO THINGS THAT MUST NOT DRIFT
 *   1. The emitted tag is a CLASSIC <script>. An inline `type="module"` is deferred by
 *      spec and would run after first paint — silently restoring the exact bug.
 *   2. This runs from `npm run build:demo`, after ui/card/build.js has rebuilt the IIFE,
 *      so the inline copy cannot fall behind the source. --check fails if any page is
 *      stale, for CI.
 *
 * The standalone attr-fallback.min.js stays: it is the documented entry for consumers.
 * layout/polyfills/attr-fallback.js is a DIFFERENT polyfill (it ships a companion
 * stylesheet) and is deliberately untouched.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const SOURCE = 'ui/base/polyfills/attr-fallback.iife.min.js';
/* AN ALLOWLIST, deliberately one page long.
 *
 * Inlining costs ~1.1 kB compressed in EVERY document that carries it, against one shared
 * cached file — so it is only worth it where a render-blocking round trip actually costs
 * something measurable. schema.html is the page the performance work is measured on; the
 * other 27 pages that load the polyfill stay on the <script src> and act as the control.
 * Widen this list only with a measurement that says the trade pays off on those pages too.
 *
 * Paths are repo-relative. A page's own builder template counts as the page: add
 * ui/card/demo/build.shared.js (HEAD_COMMON) or a builder's inline template here if the
 * generated pages ever join, or the next build run silently reverts them. */
const PAGES = ['ui/card/demo/schema.html'];

const START = '<!-- polyfill:start -->';
const END = '<!-- polyfill:end -->';
/* the <script src> this replaces on the FIRST run; after that the markers are the anchor.
   BOTH are global: a builder file can hold more than one page template (articles/build.js
   holds two), and a non-global replace silently updates only the first. */
const TAG = /[ \t]*<script[^>]*src="\/ui\/base\/polyfills\/attr-fallback\.min\.js"[^>]*><\/script>\n?/g;
const BLOCK = new RegExp(`[ \\t]*${START}[\\s\\S]*?${END}\n?`, 'g');

export function inlinePolyfill({ check = false } = {}) {
	const code = readFileSync(join(ROOT, SOURCE), 'utf8').trim();
	/* The payload lands in HTML *and* inside a JS template literal (HEAD_COMMON), so it
	   must be inert in both, since PAGES may later name a builder template. esbuild has
	   never emitted any of these, but the polyfill keeps changing — fail loudly rather
	   than silently corrupt a page. */
	for (const [needle, why] of [['</script', 'closes the inline script early'], ['`', 'breaks the HEAD_COMMON template literal'], ['${', 'interpolates inside HEAD_COMMON']]) {
		if (code.includes(needle)) throw new Error(`${SOURCE} contains ${JSON.stringify(needle)}, which ${why}. Inlining aborted.`);
	}

	const block = (indent) =>
		`${indent}${START}\n` +
		`${indent}<!-- Typed attr() polyfill, INLINE and CLASSIC on purpose: it must run before\n` +
		`${indent}     first paint (view-transition snapshot), and an inline module would defer.\n` +
		`${indent}     Generated by scripts/inline-polyfill.js — do not edit, do not add type=. -->\n` +
		`${indent}<script>${code}</script>\n` +
		`${indent}${END}\n`;

	const stale = [];
	let changed = 0;
	for (const page of PAGES) {
		const file = join(ROOT, page);
		const src = readFileSync(file, 'utf8');
		/* markers first, then any raw tag left over — the fresh block carries no src=,
		   so the second pass cannot re-match what the first just wrote. Both patterns are
		   global: one file may hold more than one occurrence. */
		const next = src
			.replace(BLOCK, (m) => block(/^[ \t]*/.exec(m)[0]))
			.replace(TAG, (m) => block(/^[ \t]*/.exec(m)[0]));
		if (next === src) continue;
		if (check) { stale.push(page); continue; }
		writeFileSync(file, next);
		changed++;
	}
	return { changed, stale, bytes: code.length };
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
	const check = process.argv.includes('--check');
	const { changed, stale, bytes } = inlinePolyfill({ check });
	if (check) {
		if (stale.length) {
			console.error(`inline polyfill is stale in ${stale.length} file(s):\n  ${stale.join('\n  ')}\n  run: node scripts/inline-polyfill.js`);
			process.exit(1);
		}
		console.log('inline polyfill: ok');
	} else {
		console.log(`inline polyfill  ${bytes} B inlined into ${changed} file${changed === 1 ? '' : 's'}`);
	}
}
